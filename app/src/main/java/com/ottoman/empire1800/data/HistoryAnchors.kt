val historyAnchors: List<String> get() = historyAnchorList.map { it.text }

private fun anchorDistanceToYear(a: HistoryAnchor, year: Int): Int = when {
    year < a.from -> a.from - year
    year > a.to -> year - a.to
    else -> 0
}

fun anchorsFor(year: Int, s: GameState? = null): List<String> =
    historyAnchorList
        .filter { a ->
            a.to >= year - 1 &&
                a.from <= year + 5 &&
                (a.skipIfDissolved == null || s?.powers?.get(a.skipIfDissolved)?.dissolved != true)
        }
        .sortedWith(
            compareBy<HistoryAnchor>(
                { anchorDistanceToYear(it, year) },
                { kotlin.math.abs(it.from - year) },
                { it.from },
            ),
        )
        .take(6)
        .map { it.text }
